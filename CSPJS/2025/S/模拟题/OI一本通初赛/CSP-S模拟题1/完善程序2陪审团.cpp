#include <cstdio>
#include <cstring>
#include <algorithm>
using namespace std;

// 动态规划数组：f[j][k]表示选j个陪审团成员时，控辩分差对应索引为k的最大总分
// 这里用索引k替代实际分差，避免负索引，后续通过偏移量转换
int f[30][1000];
// 路径记录数组：Path[j][k]记录选j个成员、分差索引为k时，最后一个选中的候选人编号
int Path[30][1000];
// P[i]：第i个候选人的控方打分（支持控方的分数）
// D[i]：第i个候选人的辩方打分（支持辩方的分数）
int P[300];
int D[300];
// Answer数组：存储最终选中的m个陪审团成员编号，用于输出
int Answer[30];

int main() {
	// 循环变量：i遍历候选人，j遍历已选人数，k遍历分差索引
	int i,j,k;
	// 临时变量：t1记录回溯时的已选人数，t2记录回溯时的分差索引
	int t1,t2;
	// n：候选人数总量，m：需要选出的陪审团成员数
	int n,m;
	// nMinP_D：分差的偏移量，用于将负分差转换为正索引（避免数组下标为负）
	int nMinP_D;
	// nCaseNo：案例编号，用于多组输入时区分不同案例
	int nCaseNo=0;
	
	// 读取第一组候选人数n和陪审团人数m
	scanf("%d%d",&n,&m);
	// 循环条件：当n和m都不为0时，处理当前案例（支持多组输入）
	while(n+m) {
		// 案例编号自增，标记当前处理的是第几个案例
		nCaseNo++;
		// 遍历所有候选人，读取每个候选人的控方打分P[i]和辩方打分D[i]
		for(i=1;i<=n;i++)
			scanf("%d%d",&P[i],&D[i]);
		
		// 初始化动态规划数组f为-1：-1表示该状态不可达（无合法选法）
		memset(f,-1,sizeof(f));
		// 初始化路径数组Path为0：0表示未记录候选人编号
		memset(Path,0,sizeof(Path));
		
		// ①：计算分差偏移量nMinP_D = m * 20
		// 原因：每个候选人的控辩分差最大为20（控方20、辩方0），m个成员的最大分差为m*20
		// 用该值作为偏移量，可将实际分差范围[-m*20, m*20]转换为索引范围[0, 2*m*20]
		nMinP_D=m*20; 
		
		// ②：初始化动态规划的初始状态f[0][nMinP_D] = 0
		// 含义：选0个成员时，控辩分差为0（实际分差=索引-偏移量：nMinP_D - nMinP_D = 0）
		// 此时总分为0（没有成员，自然没有分数），该状态是后续所有状态的起点
		f[0][nMinP_D]=0; 
		
		// 外层循环：j从0到m-1，遍历已选的陪审团成员数（逐步增加到m）
		for(j=0;j<m;j++) {
			// ③：内层循环：k从0到nMinP_D*2，遍历所有可能的分差索引
			// 原因：分差索引范围是[0, 2*nMinP_D]（对应实际分差[-nMinP_D, nMinP_D]）
			// 需遍历所有可能的索引，确保不遗漏任何可达状态
			for(k=0;k<=nMinP_D*2;k++) { 
				
				// ④：判断当前状态f[j][k]是否可达（即f[j][k] != -1）
				// 只有可达状态才能作为基础，推导后续选j+1个成员的状态
				if(f[j][k]>=0) { 
					
					// 遍历所有候选人i，尝试将i加入当前j个成员的组合中，形成j+1个成员的组合
					for(i=1;i<=n;i++) {
						// 计算加入候选人i后的新总分：当前总分f[j][k] + i的控方分P[i] + 辩方分D[i]
						// 计算加入i后的新分差索引：当前索引k + (P[i]-D[i])（P[i]-D[i]是i的实际分差）
						// ⑤：状态转移条件：新总分 > 已有j+1个成员、新分差索引对应的总分
						// 含义：如果加入i后能得到更大的总分，就更新该状态
						if(f[j][k]+P[i]+D[i]>f[j+1][k+P[i]-D[i]]) { 
							
							// 回溯检查：确保候选人i没有被重复选中
							// t1初始为当前已选人数j，t2初始为当前分差索引k
							t1=j;
							t2=k;
							// 循环回溯：从当前状态倒推，直到选0个成员，或找到已选i的记录
							while(t1>0 && Path[t1][t2]!=i) {
								// 倒推：减去上一个选中成员的分差，回到上一个状态的分差索引
								t2-=P[Path[t1][t2]]-D[Path[t1][t2]];
								// 已选人数减1，继续倒推
								t1--;
							}
							// 如果t1==0，说明回溯到选0个成员时仍未找到i，即i未被选中，可安全加入
							if(t1==0) {
								// 更新j+1个成员、新分差索引对应的最大总分
								f[j+1][k+P[i]-D[i]]=f[j][k]+P[i]+D[i];
								// 记录该状态的最后一个选中成员为i（用于后续回溯结果）
								Path[j+1][k+P[i]-D[i]]=i;
							}
						}
					}
				}
			}
		}
		
		// 寻找选m个成员时，分差绝对值最小的状态（优先选分差小的，分差相同时选总分大的）
		j=m; // 已选人数固定为m
		k=nMinP_D; // 初始从分差为0的索引开始（nMinP_D - nMinP_D = 0）
		// 循环：如果当前索引k的状态不可达，且对称索引（nMinP_D*2 -k）可达，则k减1（向负分差方向找）
		while(f[m][k]<0 && f[m][nMinP_D*2-k]>=0) k--;
		// 比较当前k和对称索引的总分，选总分更大的索引（分差绝对值相同，选总分高的）
		if(f[m][k]<f[m][nMinP_D*2-k]) k=nMinP_D*2-k;
		
		// 回溯Path数组，记录选中的m个成员编号到Answer数组
		for(i=1;i<=m;i++) {
			// ⑥：Answer[i] = Path[m - i + 1][k]
			// 含义：m-i+1是倒序的已选人数（从m到1），k是当前分差索引
			// 每次取对应状态的最后一个选中成员，存入Answer数组
			Answer[i]=Path[m-i+1][k];
			// 更新k：减去当前选中成员的分差，回到上一个状态的分差索引（继续回溯）
			k-=P[Answer[i]]-D[Answer[i]];
		}
		
		// 对选中的成员编号进行排序（题目通常要求按编号升序输出）
		sort(Answer+1,Answer+m+1);
		
		// 输出当前案例的结果
		printf("Jury #%d\n",nCaseNo);
		// 计算并输出控方总分和辩方总分：
		// 总分 = 控方分 + 辩方分 = f[m][nMinP_D*2 -k]（最终状态的总分）
		// 分差 = 控方分 - 辩方分 = (nMinP_D*2 -k) - nMinP_D = nMinP_D -k
		// 联立得：控方分 = (总分 + 分差)/2，辩方分 = (总分 - 分差)/2
		printf("Best jury has value %d for prosecution and value %d for defence:\n",
			(f[m][nMinP_D*2-k]+nMinP_D -k)/2,(f[m][nMinP_D*2-k]-(nMinP_D -k))/2);
		// 输出选中的成员编号（按升序）
		for(i=1;i<=m;i++)
			printf(" %d",Answer[i]);
		// 每组案例输出后空一行，区分不同案例
		printf("\n\n");
		
		// 读取下一组候选人数n和陪审团人数m，准备处理下一个案例
		scanf("%d%d",&n,&m);
	}
	return 0;
}
