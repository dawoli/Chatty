void f(int q,int w,long long v,int b,int c,int d){
	if(b>q/2){
		return;
	} 
	if(c>q/2){
		return;
	} 
	if(d>q/2){
		return;
	}
	if(b+c+d>q){
		return;
	}
	if(w>q){
		ans=max(ans,v);
		return;
	}
	int cnt2=max(a[w][1],max(a[w][2],a[w][3]));
	int cnt=w;
	w++;
	b++;
	v+=a[cnt][1];
	f(q,w,v,b,c,d);
	b--;
	v-=a[cnt][1];
	c++;
	v+=a[cnt][2];
	f(q,w,v,b,c,d);
	c--;
	v-=a[cnt][2];
	d++;
	v+=a[cnt][3];
	f(q,w,v,b,c,d);
	w--;
	d--;
	v-=a[w][3];
	return;
}
