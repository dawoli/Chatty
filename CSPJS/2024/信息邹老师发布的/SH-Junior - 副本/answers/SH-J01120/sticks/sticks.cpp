#include<bits/stdc++.h>
using namespace std;
long long n,i,j;
int main()
{
	freopen("sticks.in","r",stdin);
	freopen("sticks.out","w",stdout);
	cin>>n;
		for(i=1;i<=n;i++)
		{
			long long m=0,step=0,b=0;
			cin>>m;
			if(m<2)
			{
				cout<<-1<<endl;
				continue;
			}
			if(m==2)
			{
			cout<<1<<endl;
			continue;	
			}
			else
			if(m==3)
			{
			cout<<7<<endl;
				continue;	
			}
			else
			if(m==4)
			{
			cout<<4<<endl;
				continue;	
			}
			else
			if(m==5)
			{
			cout<<2<<endl;
				continue;	
			}
			else
			if(m==6)
			{
			cout<<6<<endl;
			continue;	
			}
			step=ceil(m/7.0);
			b=m%7;
			if(b==0||b==2)
			{
				if(b==2)
				cout<<1;
				for(j=1;j<step;j++)
				cout<<8;
				if(b==0)
				cout<<8;
				cout<<endl;
				continue;
			}
			if(b==1)
			{
				cout<<10;
				for(j=1;j<step-1;j++)
				cout<<8;
				cout<<endl;
				continue;
			}
			if(b==3)
			{
				if(step>=3)
				{
				cout<<200;
				for(j=1;j<step-2;j++)
				cout<<8;	
				}
				else
				{
				cout<<22;
				}
				cout<<endl;
				continue;	
			}
			if(b==4)
			{
				cout<<20;
				for(j=1;j<step-1;j++)
				cout<<8;
				cout<<endl;
				continue;	
			}
			if(b==5)
			{
				cout<<2;
				for(j=1;j<step;j++)
				cout<<8;
				cout<<endl;
				continue;	
			}
			if(b==6)
			{
				cout<<6;
				for(j=1;j<step;j++)
				cout<<8;
				cout<<endl;
				continue;	
			}
		}
		return 0;
}
