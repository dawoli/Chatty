#include <bits/stdc++.h>
using namespace std;
int main()
{
	freopen("sticks.in","r",stdin);
	freopen("sticks.out","w",stdout);
	int t;
	int n,ws,w;
	scanf("%d",&t);
	while(t--)
	{
		w=1;
		scanf("%d",&n);
		ws=(n+6)/7;
		if(n==1)
		{
			printf("-1");
			if(t>=1) printf("\n");
			continue;
		}
		for(int i=1;i<=ws;i++)
		{
			if(i==ws)
			{
				if(n==7)
				{
					printf("8");
					break;
				}
				if(n==6&&ws!=1)
				{
					printf("0");
					break;
				}
				if(n==6)
				{
					printf("6");
					break;
				}
				if(n==5)
				{
					printf("2");
					break;
				}
				if(n==4)
				{
					printf("4");
					break;
				}
				if(n==3)
				{
					printf("7");
					break;
				}
				if(n==2)
				{
					printf("1");
					break;
				}
			}
			if(w!=1&&n%7!=0&&n>=6)
			{
				printf("0");
				n-=6;
				w++;
				continue;
			}
			if(n%7!=0&&n%7<3&&n>=2)
			{
				printf("1");
				n-=2;
				w++;
				continue;
			}
			if(n%7!=0&&n%7<6&&n>=5)
			{
				printf("2");
				n-=5;
				w++;
				continue;
			}
			if(n%7!=0&&n%7<5&&n>=4)
			{
				printf("4");
				n-=4;
				w++;
				continue;
			}
			if(n%7!=0&&n%7<4&&n>=3)
			{
				printf("7");
				n-=3;
				w++;
				continue;
			}
			if(n%7!=0&&n>=6)
			{
				printf("6");
				n-=6;
				w++;
				continue;
			}
			if(n%7==0)
			{
				printf("8");
				n-=7;
				w++;
				continue;
			}
		}
		if(t>=1) printf("\n");
	}
	return 0;
}
