#include<bits/stdc++.h>
using namespace std;

long long t,n;

int main()
{
    freopen("sticks.in","r",stdin);
    freopen("sticks.out","w",stdout);
    cin>>t;
    while(t--)
    {
        cin>>n;
        if(n<2)
        {
            cout<<-1<<endl;
            continue;
        }
        if(n==3)
        {
            cout<<7<<endl;
            continue;
        }
        if(n==4)
        {
            cout<<4<<endl;
            continue;
        }
        if(n%7==1)
        {
            n-=8;
            if(n<0)
            {
                cout<<-1<<endl;
                continue;
            }
            cout<<10;
        }
        if(n%7==2)
        {
            n-=2;
            if(n<0)
            {
                cout<<-1<<endl;
                continue;
            }
            cout<<1;
        }
        if(n%7==3)
        {
            n-=10;
            if(n<0)
            {
                cout<<-1<<endl;
                continue;
            }
            cout<<22;
        }
        if(n%7==4)
        {
            n-=11;
            if(n<0)
            {
                cout<<-1<<endl;
                continue;
            }
            cout<<20;
        }
        if(n%7==5)
        {
            n-=5;
            if(n<0)
            {
                cout<<-1<<endl;
                continue;
            }
            cout<<2;
        }
        if(n%7==6)
        {
            n-=6;
            if(n<0)
            {
                cout<<-1<<endl;
                continue;
            }
            cout<<6;
        }
        while(n!=0)
        {
            cout<<8;
            n-=7;
        }
        cout<<endl;
    }
    fclose(stdin);
    fclose(stdout);
    return 0;
}
