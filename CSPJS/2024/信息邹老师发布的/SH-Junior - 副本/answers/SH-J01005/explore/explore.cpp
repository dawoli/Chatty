#include<bits/stdc++.h>
using namespace std;
char a[1005][1005];
int vis[1005][1005];
int dfs(int x,int y,int d,int cnt,int n,int m,int k){
    if(k<=0){
        return cnt;
    }

    if(d==0){
        if(y+1>m||a[x][y+1]=='x'){
            d=(d+1)%4;
//            cout<<d<<'\n';
            return dfs(x,y,d,cnt,n,m,k-1);
        }
    }
    if(d==1){
        if(x+1>n||a[x+1][y]=='x'){
            d=(d+1)%4;
//            cout<<d<<'\n';
            return dfs(x,y,d,cnt,n,m,k-1);
        }
    }
    if(d==2){
        if(y-1<=0||a[x][y-1]=='x'){
            d=(d+1)%4;
//            cout<<d<<'\n';
            return dfs(x,y,d,cnt,n,m,k-1);
        }
    }
    if(d==3){
        if(x-1<=0||a[x-1][y]=='x'){
            d=(d+1)%4;
//            cout<<d<<'\n';
            return dfs(x,y,d,cnt,n,m,k-1);
        }
    }
    if(d==0){
        y++;
    }
    if(d==1){
        x++;
    }
    if(d==2){
        y--;
    }
    if(d==3){
        x--;
    }
//    cout<<x<<' '<<y<<' '<<k<<'\n';
    if(vis[x][y]!=0){
    	return dfs(x,y,d,cnt,n,m,k-1);
	}else{
		vis[x][y]++;
		return dfs(x,y,d,cnt+1,n,m,k-1);
	}

}
