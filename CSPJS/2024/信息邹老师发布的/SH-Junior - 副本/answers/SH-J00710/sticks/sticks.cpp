#include <bits/stdc++.h>
using namespace std;
int T,i;
long long n,x,k,a[1000001];
int main()
{
	freopen("sticks.in","r",stdin);
	freopen("sticks.out","w",stdout);
	cin>>T;
	while(T--)
	{
		x=0,k=0;
		cin>>n;
		if(n%7==0)
		{
			while(n>0)
			{
				n-=7;
				cout<<8;
			}
			cout<<"\n";
			continue;
		}
		if(n<=1)
		{
			cout<<"-1\n";
			continue;;
		}
		bool flag=0;
		while(n>0)
		{
			if(n==8)
			{
				cout<<"10\n";
				flag=1;
				break;
			}
			if(n==2)
			{
				a[k]=1;
				k++;
				n=0;
				continue;
			}
			if(n==3)
			{
				a[k]=7;
				k++;
				n=0;
				continue;
			}
			if(n==4)
			{
				a[k]=4;
				k++;
				n=0;
				continue;
			}
			if(n==5)
			{
				a[k]=2;
				k++;
				n=0;
				continue;
			}
			if(n==6)
			{
				if(k<1)
					a[k]=6;
				else
					x++;
				k++;
				n=0;
				continue;
			}
			if(n==7)
			{
				a[k]=8;
				k++;
				n=0;
				continue;
			}
			if(n>7)
			{
				if(n/6==n/7&&k>0)
					x++,n-=6;
				else
					a[k]=8,n-=7,k++;
				
				continue;
			}
		}
		if(flag==1)
			continue;
		sort(a,a+k);
		cout<<a[0];
		for(i=1;i<=x;i++)
			cout<<0;
		for(i=1;i<k;i++)
			cout<<a[i];
		cout<<"\n";
	}
	return 0;
}
