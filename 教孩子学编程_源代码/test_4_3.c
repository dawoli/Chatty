#include <stdio.h>
#include <stdlib.h>
int main()
{
	int n;     //整数
    double x;  //浮点数
    n = 9.99;
    x = 9.99;
    printf(" int  型变量n的值：%d\n",n);
    printf("             n/2 = %d\n",n/2);
    printf("double型变量x的值：%f\n",x);
    printf("           x/2.0 = %f\n",x/2.0);
	system("pause");
	return 0;
}
