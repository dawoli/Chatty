// 包含所有常用标准库（竞赛中简化写法，无需单独引入iostream、algorithm等）
#include <bits/stdc++.h>
// 使用std命名空间，避免每次写std::前缀
using namespace std;

// 全局变量定义：
// n：饮料的总种类数；L：需要满足的最小总容量；
// c[509]：存储每种饮料的售价（cost）；l[509]：存储每种饮料的容量（length/volume）；
// f[2009]：DP数组，优化版定义——f[j]表示“满足总容量≥j”所需的最小花费（核心优化点）
int n, L, c[509], l[509];
int f[2009];

int main()
{
	// 输入饮料种类数n和需要的最小总容量L
	cin >> n >> L;

	// 遍历输入每种饮料的售价和容量（下标从1开始，符合竞赛常用写法）
	for (int i = 1; i <= n; i++)
		cin >> c[i] >> l[i]; // c[i] = 第i种饮料的售价，l[i] = 第i种饮料的容量

	// 初始化DP数组：将所有元素设为极大值0x3f3f3f3f（表示初始时“无法满足该容量要求”）
	// 0x3f3f3f3f是竞赛常用极大值，约1e9，远大于题目中可能的花费上限
	memset(f , 0x3f , sizeof(f));
	// 边界条件：满足“总容量≥0”的最小花费为0（选0瓶饮料即可）
	f[0] = 0;

	// 01背包核心循环：遍历每一种饮料（每种只能选1次）
	for(int i = 1; i <= n; i++)
	{
		// 优化版内层循环：仅遍历到L即可（无需遍历到最大容量）
		// j从L逆序遍历到0（逆序避免同一饮料被重复选择）
		for(int j = L; j >= 0; j--)
		{
			// 状态转移方程（核心优化）：
			// max(0, j - l[i])：若选当前饮料后，需要满足的剩余容量≤0，说明已满足≥j的要求，取0即可
			// 含义：满足≥j容量的最小花费 = min(不选当前饮料的花费f[j], 选当前饮料的花费f[剩余需满足容量]+c[i])
			f[j] = min(f[j] , f[max(0 , j - l[i])] + c[i]);
		}
	}

	// 判断是否有解：f[L]为极大值说明无法满足≥L的容量要求
	if(f[L] != 0x3f3f3f3f)
		cout << f[L]; // 输出满足≥L容量的最小花费
	else
		cout << "no solution"; // 输出无解

	return 0;
}