#include <bits/stdc++.h>
#define int long long
using namespace std;

int							   n, x, tx, D;						 // n:总房数  x:当前剩余油(会随过程变化)
																 // tx:初始油量(保存后恒不变)  D:能到达的最远房号
int							   d[500005], f[500005], tf[500005]; // d:每间房的耗油  f:每间房初始燃料
																 // tf:f 的副本(只在求 D 时用)
int							   qz[500005], qzd[500005];			 // qz:f 的前缀和  qzd:d 的前缀和(用于第二部分判断)
int							   exs, cnt;						 // exs:通过交换额外获得的总油量  cnt:交换次数(=答案S)
priority_queue<pair<int, int>> Q;								 // 大根堆: 每个元素 {交换该对称位的收益, -位置}

// * 函数: 从堆顶取一次"交换"并生效, 返回本次收益
int applyGain(priority_queue<pair<int, int>> &pq)
{								 // 传引用, 直接改原堆和原数组
	pair<int, int> t = pq.top(); // 取堆顶(收益最大的那个候选), 注意这是 pair
	pq.pop();					 // 弹出堆顶, 因为它已被使用
	int p = -t.second;			 // 还原位置: 存的本来是 -i, 取负得回 i
	swap(f[p], f[n - p + 1]);	 // 把位置 p 和他对称位 n-p+1 的燃料互换
	return t.first;				 // 返回本次交换带来的收益(=换来的多余燃料)
}

signed main()
{
	ios::sync_with_stdio(false);
	cin.tie(0);
	cout.tie(0);

	cin >> n >> x; // 读入房间数 n 和初始油量 x
	tx = x;		   // 把初始油量存到 tx, 后面要用它做判断
	for (int i = 1; i <= n; i++)
		cin >> d[i]; // 读入每间房的耗油 d[i]
	for (int i = 1; i <= n; i++)
	{
		cin >> f[i];  // 读入每间房的燃料 f[i]
		tf[i] = f[i]; // 同时复制到 tf[i], 供求 D 时单独使用
	}

	// *  ==================== 第一部分: 求 D (能到达的最远房号) ====================
	// * 思路: 每个"对称位"(i, n-i+1) 如果允许交换,
	// * 把较大的燃料换到较近的一侧, 就能走得最远。
	// * 先假设"可以任意交换", 求出最远能到哪, 记作 D。
	for (int i = 1; (i << 1) <= n; i++) // 遍历到 n/2 为止 (i<<1 <= n 等价于 i <= n/2)
		if (tf[i] < tf[n - i + 1])		// 如果靠远的一侧燃料比靠近的多
			swap(tf[i], tf[n - i + 1]); // 就把大的换到较近的一侧 (用 tf 副本)

	int fuel = x; // 用独立变量 fuel 模拟行军, 不污染真正的 x
	D		 = 0; // 先假设一栋都到不了
	for (int i = 1; i <= n; i++)
	{				  // 从第 1 间走到第 n 间
		fuel -= d[i]; // 走进第 i 间, 先扣掉这间的耗油
		if (fuel < 0)
			break;	   // 油不够了, 走不进这一间, 提前停止
		fuel += tf[i]; // 成功进入, 收集这一间的燃料
		D = i;		   // 更新当前能到达的最远房号
	}
	cout << D << " "; // 输出答案1: 最远房号 D

	// * ==================== 第二部分: 求 S (到达 D 的最少交换次数) ====================
	// * 思路(贪心): 用大根堆维护每个对称位"若交换"的收益 f[对称]-f[本位]。
	// * 当油不够走下一步时, 就取收益最大的那个交换来补油。
	// * 做一次交换, 次数 cnt 加 1。
	for (int i = 1; i <= n; i++)		// 预处理两个前缀和数组
		qz[i]	   = qz[i - 1] + f[i],	// qz[i] = f[1..i] 的和
			qzd[i] = qzd[i - 1] + d[i]; // qzd[i] = d[1..i] 的和

	x = tx; // 让 x 重新等于初始油量, 从头开始模拟
	for (int i = 1; i <= min(D, n / 2); i++)
	{						// 只需要处理到 D 和 n/2 的较小者
		x -= d[i];			// 走进第 i 间, 先扣耗油
		int ii = n - i + 1; // ii 是 i 的对称房号

		// * (A) 进房后若油为负: 不断用收益最大的交换来补油
		while (x < 0 && !Q.empty())
		{						  // 油不够, 且堆里还有可交换的对
			int g = applyGain(Q); // 做一次交换, 得到收益 g
			x += g;				  // 当前油量加上这次收益
			exs += g;			  // 累计"通过交换额外得到"的油
			++cnt;				  // 交换次数 +1 (这就是最终答案 S 的累计)
		}

		// * 把当前这一对对称位"如果交换"的收益加入堆(只有正的才值得加)
		if ((i << 1) <= n && f[i] < f[n - i + 1])		// i 有对称位, 且换过来有正收益
			Q.push(make_pair(f[n - i + 1] - f[i], -i)); // 存收益和 -位置

		x += f[i]; // 收集第 i 间自己的燃料

		// * ===== (B) 远端可达性检查：防止交换把后半程的油搬空 =====
		// * 换成前缀和模型看：令 /// [b_j] = tx + qz[j-1] - qzd[j]，
		// * 即"不做任何交换时，进入第 j 间房那一刻的余油"，于是 能进入第 j 间 <=> b_j >= 0。
		// * 一次交换第 p 对  <=>  对 b[p+1 .. n-p+1] 整体做 /// [区间加] gain = f[n-p+1] - f[p]。
		// * 所以第 j 个位置可用的交换是一个前缀 p ∈ [1, min(j-1, n-j+1)]：
		// * 前一半 j 的上限 j-1 递增，后一半 j 的上限 n-j+1 递减，
		// * 限制从松到紧的顺序恰好是 (2,n), (3,n-1), (4,n-2) ... —— (A) 管前一半，(B) 管后一半。
		// ! 为什么非查不可：主循环只跑到 n/2，后半段没人遍历；
		// ! 而且 x 只算到当前位置，看不见 i+1..ii-1 那段燃料能否接上
		// ! （样例 4 就是：走到第 2 间还有富余，却已经注定到不了第 5 间）。
		while (ii <= D && qz[ii - 1] + tx + exs < qzd[ii] && !Q.empty())
		{
			// * 条件 qz[ii-1] + tx + exs < qzd[ii] 等价于 b_ii + exs < 0：
			// * 把已做交换的收益全算上，进第 ii 间时油仍然为负。
			// * 能用累计量 exs 而不逐个判断，是因为此刻做过/待做的 p 全都 <= i，
			// * 而 b_ii 的可用上限 min(ii-1, i) 恰好就是 i —— 每个已做交换对它都有效，一个不浪费。
			// * 中间 i+1..ii-1 不必单独查：前半段由后续轮次的 (A) 兜住，
			// * 后半段在更早的轮次已作为 ii 被查过（ii 从 n 递减到 n/2+1，每个位置恰好查一次）。
			// * ii > D 直接跳过：b_ii 只决定"能否到第 ii 间"，D 之外没有意义。
			// * 用 while 而非 if：一次交换未必够，取完还要重新判断。
			int g = applyGain(Q); // 又做一次交换
			x += g;				  // 补进当前油量，服务后续 (A) 段的模拟
			exs += g;			  // 累计额外油，供下一轮 (B) 的条件判断
			++cnt;				  // 次数 +1
		}
	}
	cout << cnt; // 输出答案2: 最少交换次数 S
	return 0;
}