// 题面：
// 给定一个长为 n 的 01 串，你需要将其划分为两个子序列（可以为空），使其分别视为二进制数后的和最小。特别地，若子序列为空，则将其视为二进制数 0。以二进制形式输出这个最小的和。
// 多组数据，n之和 < 5e5

#include <bits/stdc++.h>
using namespace std;

int main()
{
	ios::sync_with_stdio(false);
	cin.tie(0);

	int T;
	cin >> T;
	while (T--)
	{
		int	   n;	   // 二进制串的长度
		string s;	   // 二进制串本身
		cin >> n >> s; // 读入长度和二进制串

		// * ---------- 第一阶段：统计 '1' 的个数，并寻找分界位置 ----------
		int	 cnt   = 0;		// cnt：已经遇到（含当前）的 '1' 的个数
		int	 pos   = n;		// 分界位置，初始化为 n（末尾之外）
		bool found = false; // 是否已找到分界位置的标记

		for (int i = 0; i < n; ++i)
		{ // 从最高位（下标0）往低位遍历
			if (s[i] == '1')
				++cnt; // 遇到 '1' 就累加计数

			// TODO: 理解下面这个分界条件的意义
			// * 分界条件：当前位是 '1'，且"从当前位置到末尾的剩余位数 ≤ 已收集到的 1 的个数"
			// 剩余位数 = n - i（含当前位）
			if (!found && s[i] == '1' && (n - i) <= cnt)
			{
				pos	  = i;	  // 记录最早满足条件的位置
				found = true; // 标记已找到，后续不再更新
			}
		}

		// * ---------- 特判：整个串全是 '0' ----------
		if (cnt == 0)
		{				   // 一个 '1' 都没有
			cout << "0\n"; // 两数之和只能是 0，直接输出
			continue;	   // 跳过本组，进入下一组
		}

		// * ---------- 第二阶段：根据分界构造两个二进制数 ----------
		// s2 = 分界位置及之后的所有字符（原样保留）
		string s2 = found ? s.substr(pos) : ""; // 若没找到 s2 为空

		// s1 = 分界位置之前的所有 '1'（去掉所有的 '0'，只拼 '1'）
		string s1;					  // 初始为空
		for (int i = 0; i < pos; ++i) // 遍历分界之前的部分
			if (s[i] == '1')
				s1 += '1'; // 只把 '1' 拼进来

		// * 边界保护：若某一边为空，则视作 "0"
		if (s1.empty())
			s1 = "0"; // 分界前没有 1 → s1 为 0
		if (s2.empty())
			s2 = "0"; // 分界后为空 → s2 为 0

		// * ---------- 第三阶段：二进制加法（从最低位对齐相加） ----------
		int	   i1	 = s1.size() - 1; // 指向 s1 的最低位（字符串末尾）
		int	   i2	 = s2.size() - 1; // 指向 s2 的最低位（字符串末尾）
		int	   carry = 0;			  // carry：进位，初始为 0
		string res;					  // res：累加结果（先低位在前）

		while (i1 >= 0 || i2 >= 0)
		{ // 两个数都还没加完
			// * 取当前位，越界的位按 0 处理（省去补前导 0）
			int b1	= (i1 >= 0) ? s1[i1] - '0' : 0; // s1 当前位数字
			int b2	= (i2 >= 0) ? s2[i2] - '0' : 0; // s2 当前位数字
			int sum = b1 + b2 + carry;				// 当前位求和（含进位）
			res += char('0' + sum % 2);				// 本位结果（0 或 1），追加到低位
			carry = sum / 2;						// 更新进位（满 2 进 1）
			--i1;
			--i2; // 两个指针各向前移动一位（更高位）
		}

		if (carry)
			// * 两数加完仍有进位 → 补一个最高位 1
			res += '1';

		// * 结果是低位在前，反转成高位在前
		reverse(res.begin(), res.end());
		cout << res << "\n"; // 输出最终之和
	}
	return 0; // 主函数正常返回
}